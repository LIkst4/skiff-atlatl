"""SYNTH's tables (eng_synth.c): the wavetable (8 waves x 2 band limits x 128 points, int16) and the additive engine's
partial levels (33 brightness steps x 16 partials, Q15). Writes firmware/src/synth_tables.h"""
import math, os
N = 128
LIMITS = (32, 8)             # harmonics kept: low notes, mid, high (eng_synth.c picks by the pitch)

def wave(spec, lim):
    """spec: harmonic -> (amplitude, phase); summed up to lim harmonics, normalised to 32000"""
    s = [0.0] * N
    for h, (a, ph) in spec.items():
        if h > lim or a == 0:
            continue
        for i in range(N):
            s[i] += a * math.sin(2 * math.pi * h * i / N + ph)
    pk = max(abs(x) for x in s) or 1.0
    return [int(round(x / pk * 32000)) for x in s]

H = range(1, 65)
WAVES = [
    ("SINE", {1: (1, 0)}),
    ("TRI", {h: ((-1) ** ((h - 1) // 2) / h ** 2, 0) for h in H if h % 2}),
    ("SAW", {h: (1 / h, 0) for h in H}),
    ("SQUARE", {h: (1 / h, 0) for h in H if h % 2}),
    ("PULSE", {h: (math.sin(math.pi * h * 0.25) / h, 0) for h in H}),            # 25 %
    ("ORGAN", {1: (1, 0), 2: (0.8, 0), 3: (0.6, 0), 4: (0.5, 0), 6: (0.35, 0), 8: (0.3, 0), 16: (0.12, 0)}),
    ("VOX", {h: (math.exp(-((h - 3) / 1.6) ** 2) + 0.6 * math.exp(-((h - 9) / 2.0) ** 2) +
                 0.25 * math.exp(-((h - 17) / 3.0) ** 2) + 0.05 / h, 0) for h in H}),
    ("DIGI", {h: (1.0 / (1 + (h // 4) * 0.35), 0) for h in H if h % 4 == 1}),
]
out = ["/* generated by tools/gen_synth_tables.py: do not edit */",
       "#define SYN_WN %d                 /* waves */" % len(WAVES),
       "#define SYN_WL %d                 /* band limits: %s harmonics */" % (len(LIMITS), ", ".join(map(str, LIMITS))),
       "static const int16_t SYN_WT[%d][%d][%d] = {" % (len(WAVES), len(LIMITS), N)]
for name, spec in WAVES:
    out.append("    {   /* %s */" % name)
    for lim in LIMITS:
        w = wave(spec, lim)
        out.append("        {" + ", ".join(map(str, w)) + "},")
    out.append("    },")
out.append("};")
out.append("static const char *const N_SYN_WAVE[%d] = {%s};" % (len(WAVES), ", ".join('"%s"' % w[0] for w in WAVES)))
# additive: partial k (1..16) at brightness b (0..32): k ^ -(3.0 - 2.7 b / 32), normalised so their sum is 1 (Q15)
out.append("static const int16_t SYN_ADD[33][16] = {")
for b in range(33):
    p = 3.0 - 2.7 * b / 32
    a = [k ** -p for k in range(1, 17)]
    s = sum(a)
    out.append("    {" + ", ".join(str(int(round(x / s * 32767))) for x in a) + "},")
out.append("};")
p = os.path.join(os.path.dirname(__file__), "..", "firmware", "src", "synth_tables.h")
open(p, "w").write("\n".join(out) + "\n")
print("synth tables ->", os.path.normpath(p))
