"""flt.c's tables: the cutoff law (index 0..1024 -> 20 Hz .. ~17.8 kHz, 9.8 octaves) as g = tan(pi f / fs) in Q12,
and the vowel formants as cutoff indexes. Writes firmware/src/flt_tables.h."""
import math, os
FS = 44100.0
OCT = 9.8
def freq(i): return 20.0 * 2 ** (i / 1024.0 * OCT)
def index(f): return int(round(1024.0 * math.log2(f / 20.0) / OCT))
g = [min(int(round(math.tan(math.pi * min(freq(i), 0.45 * FS) / FS) * 4096)), 32000) for i in range(1025)]
# formants (F1 F2 F3, Hz) of A E I O U and their levels (Q15)
VOW = [(730, 1090, 2440), (530, 1840, 2480), (270, 2290, 3010), (570, 840, 2410), (300, 870, 2240)]
out = ["/* generated by tools/gen_flt_tables.py: do not edit */",
       "static const uint16_t FLT_G[1025] = {"]
for k in range(0, 1025, 16):
    out.append("    " + ", ".join(str(v) for v in g[k:k + 16]) + ",")
out.append("};")
out.append("static const int16_t FLT_VOWEL[5][3] = {")
for v in VOW:
    out.append("    {" + ", ".join(str(index(f)) for f in v) + "},")
out.append("};")
out.append("#define FLT_IDX_HZ(f) /* (host tools) */ 0")
p = os.path.join(os.path.dirname(__file__), "..", "firmware", "src", "flt_tables.h")
open(p, "w").write("\n".join(out) + "\n")
print("flt tables ->", os.path.normpath(p))
